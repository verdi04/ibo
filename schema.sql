-- ============================================================
-- 1. جدول الأجهزة (devices)
-- يخزن عناوين الماك، مفاتيح الأجهزة، حالة الاشتراك وتواريخ الانتهاء
-- ============================================================
CREATE TABLE IF NOT EXISTS devices (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mac_address      VARCHAR(17)  NOT NULL UNIQUE,
    device_key       VARCHAR(10)  NOT NULL UNIQUE,
    status           VARCHAR(20)  NOT NULL DEFAULT 'trial',
    -- status يأخذ إحدى القيم: 'trial' | 'active' | 'expired'
    trial_ends_at    TIMESTAMPTZ,
    license_expires_at TIMESTAMPTZ,
    device_type      VARCHAR(50)  DEFAULT 'Android TV',
    last_seen_at     TIMESTAMPTZ  DEFAULT NOW(),
    created_at       TIMESTAMPTZ  DEFAULT NOW(),
    updated_at       TIMESTAMPTZ  DEFAULT NOW()
);

-- فهارس لتسريع البحث في جدول الأجهزة
CREATE INDEX IF NOT EXISTS idx_devices_mac ON devices (mac_address);
CREATE INDEX IF NOT EXISTS idx_devices_key ON devices (device_key);
CREATE INDEX IF NOT EXISTS idx_devices_status ON devices (status);

-- ============================================================
-- 2. جدول قوائم التشغيل (playlists)
-- يخزن باقات M3U وبيانات حسابات Xtream Codes لكل جهاز
-- ============================================================
CREATE TABLE IF NOT EXISTS playlists (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id   BIGINT       NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    name        VARCHAR(100) NOT NULL,
    type        VARCHAR(20)  NOT NULL DEFAULT 'xtream',
    -- type يأخذ: 'xtream' | 'm3u'
    url         TEXT         NOT NULL,
    username    TEXT,
    password    TEXT,
    -- كلمة المرور مشفرة بالخوارزمية: enc:<iv>:<tag>:<ciphertext>
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  DEFAULT NOW(),
    updated_at  TIMESTAMPTZ  DEFAULT NOW()
);

-- فهارس لتسريع جلب قوائم جهاز معين
CREATE INDEX IF NOT EXISTS idx_playlists_device_id ON playlists (device_id);
CREATE INDEX IF NOT EXISTS idx_playlists_active    ON playlists (device_id, is_active);

-- ============================================================
-- 3. تفعيل أمان الصفوف (Row Level Security)
-- يمنع أي وصول مباشر لقاعدة البيانات من المتصفح دون المرور بالـ API
-- Policies مقيدة بدور service_role فقط: مفتاح anon لا يملك أي وصول،
-- والوصول يتم حصراً من routes الخادم الذي يستخدم SUPABASE_SERVICE_ROLE_KEY
-- ============================================================
ALTER TABLE devices   ENABLE ROW LEVEL SECURITY;
ALTER TABLE playlists ENABLE ROW LEVEL SECURITY;

-- سياسة الوصول لجدول الأجهزة عبر مفتاح service_role فقط
DROP POLICY IF EXISTS "devices_server_access" ON devices;
CREATE POLICY "devices_server_access" ON devices
    FOR ALL TO service_role
    USING (true)
    WITH CHECK (true);

-- سياسة الوصول لجدول القوائم عبر مفتاح service_role فقط
DROP POLICY IF EXISTS "playlists_server_access" ON playlists;
CREATE POLICY "playlists_server_access" ON playlists
    FOR ALL TO service_role
    USING (true)
    WITH CHECK (true);

-- ============================================================
-- 4. دالة تحديث updated_at تلقائياً عند أي تعديل
-- ============================================================
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ربط الدالة بجدول devices
DROP TRIGGER IF EXISTS trigger_devices_updated_at ON devices;
CREATE TRIGGER trigger_devices_updated_at
    BEFORE UPDATE ON devices
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

-- ربط الدالة بجدول playlists
DROP TRIGGER IF EXISTS trigger_playlists_updated_at ON playlists;
CREATE TRIGGER trigger_playlists_updated_at
    BEFORE UPDATE ON playlists
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

